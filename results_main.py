#!/usr/bin/env python3
"""
Parse main/report.json files from tabpack-ag experiments.

Unlike `results_eval.py` (which reads the multi-seed `evaluation/report.json`),
this reads the single-run `main/report.json` produced by
`bin/tabpack/tabpack.py`. It extracts the greedy online-ensemble test score:

  exp/{variant}/0/{experiment}/main/report.json
  → online_ensembles.greedy.report.metrics.test.score

The `{experiment}` directory name (e.g. `peru`, `peru__cosine__d1024`) is used
as the row label, so branches generated by `make_configs_branch.py` show up
side by side.

Usage:
    uv run results_main.py
    uv run results_main.py --exp-dir exp/tabpack/0 --datasets peru peru__cosine__d1024
    uv run results_main.py --variants tabpack tabpack-cosine
"""

import argparse
import json
from pathlib import Path
from typing import Optional

# ── configuration ─────────────────────────────────────────────────────────────

BASE_DIR = Path(__file__).parent

# All known experiment variants (in display order)
ALL_VARIANTS = ['tabpack', 'tabpack-cosine']

VARIANT_LABELS = {
    'tabpack': 'tabpack (MuonAdamW)',
    'tabpack-cosine': 'tabpack-cosine (cosine embeddings + MuonAdamW)',
}


def discover_datasets(exp_dir: Path) -> list[str]:
    """Find all experiment dirs that have a completed main/report.json."""
    datasets = []
    if not exp_dir.exists():
        return datasets
    for dataset_dir in sorted(exp_dir.iterdir()):
        report_path = dataset_dir / 'main' / 'report.json'
        if report_path.exists():
            datasets.append(dataset_dir.name)
    return datasets


def _load_report(report_path: Path) -> Optional[dict]:
    try:
        return json.loads(report_path.read_text(encoding='utf-8'))
    except Exception as e:
        print(f'[ERROR] Failed to read {report_path}: {e}')
        return None


def extract_score(report_path: Path, ensemble: str = 'greedy') -> Optional[float]:
    """
    Extract the greedy online-ensemble test score from main/report.json.

    The score lives at:
      report['online_ensembles'][ensemble]['report']['metrics']['test']['score']

    For metrics where higher is better (accuracy, roc-auc, r2), the score is
    already positive. For metrics where lower is better (rmse, mae,
    cross-entropy) it is stored as negative → abs() to get the actual value.
    """
    report = _load_report(report_path)
    if report is None:
        return None

    try:
        metrics = report['online_ensembles'][ensemble]['report']['metrics']
        score = metrics['test']['score']
        return abs(float(score))
    except (KeyError, TypeError, ValueError) as e:
        print(f'[WARN] Missing/invalid score ({e}) in {report_path}')
        return None


def get_metric_name(report_path: Path, ensemble: str = 'greedy') -> str:
    """
    Identify the primary metric — the one whose absolute value matches |score|.
    Falls back to listing scalar numeric keys if nothing matches.
    """
    report = _load_report(report_path)
    if report is None:
        return '?'
    try:
        metrics = (
            report['online_ensembles'][ensemble]['report']['metrics']['test']
        )
        score = abs(float(metrics['score']))
        for key, val in metrics.items():
            if key == 'score':
                continue
            try:
                if abs(abs(float(val)) - score) < 1e-9:
                    return key
            except (TypeError, ValueError):
                continue
        scalar_keys = [
            k for k, v in metrics.items()
            if k != 'score' and isinstance(v, (int, float))
        ]
        return ', '.join(scalar_keys) if scalar_keys else '?'
    except Exception:
        return '?'


def collect_results(exp_dir: Path, datasets: list[str], ensemble: str) -> tuple[
    dict[str, Optional[float]], dict[str, str]
]:
    """Collect the score and metric name for each experiment dir."""
    results: dict[str, Optional[float]] = {}
    metric_names: dict[str, str] = {}

    for dataset in datasets:
        report_path = exp_dir / dataset / 'main' / 'report.json'
        if not report_path.exists():
            print(f'[MISSING] {report_path}')
            results[dataset] = None
            metric_names[dataset] = '?'
            continue

        results[dataset] = extract_score(report_path, ensemble)
        metric_names[dataset] = get_metric_name(report_path, ensemble)

    return results, metric_names


def print_section(label: str, datasets: list[str],
                  results: dict[str, Optional[float]],
                  metric_names: dict[str, str]) -> None:
    """Pretty-print an experiment → score table for one variant."""
    HW = max((len(d) for d in datasets), default=7)
    HW = max(HW, len('Experiment')) + 2
    MW = 16   # metric column width
    SW = 14   # score column width

    print(f'\n{"=" * (HW + MW + SW)}')
    print(f'  {label}')
    print(f'{"=" * (HW + MW + SW)}')

    print(f'{"Experiment":<{HW}}{"Metric":<{MW}}{"Test score":>{SW}}')
    print('-' * (HW + MW + SW))

    for dataset in datasets:
        score = results[dataset]
        metric = metric_names.get(dataset, '?')
        cell = f'{score:.6f}' if score is not None else 'N/A'
        print(f'{dataset:<{HW}}{metric:<{MW}}{cell:>{SW}}')


# ── argument parsing ───────────────────────────────────────────────────────────

parser = argparse.ArgumentParser(description='Parse tabpack-ag main/report.json results')
parser.add_argument('--exp-dir', type=Path, default=None,
                    help='Path to a single exp/variant/0 directory (overrides --variants)')
parser.add_argument('--variants', nargs='+', default=ALL_VARIANTS,
                    help=f'Experiment variants to parse (default: {ALL_VARIANTS})')
parser.add_argument('--datasets', nargs='+', default=None,
                    help='Experiment dirs to include (default: all discovered)')
parser.add_argument('--ensemble', default='greedy',
                    help='Online ensemble name (default: greedy)')
parser.add_argument('--tsv', type=Path, default=None,
                    help='Path to write TSV output (default: exp/results_main.tsv)')
args = parser.parse_args()

ensemble: str = args.ensemble

# ── build list of (variant_label, exp_dir) pairs ──────────────────────────────

if args.exp_dir is not None:
    # Legacy single-directory mode
    run_list = [(args.exp_dir.parent.parent.name, args.exp_dir)]
else:
    run_list = [
        (variant, BASE_DIR / 'exp' / variant / '0')
        for variant in args.variants
    ]

# ── iterate over variants ──────────────────────────────────────────────────────

all_tsv_rows: list[str] = []

for variant, exp_dir in run_list:
    if not exp_dir.exists():
        print(f'[SKIP] {exp_dir} does not exist')
        continue

    if args.datasets:
        datasets = args.datasets
    else:
        datasets = discover_datasets(exp_dir)

    if not datasets:
        print(f'[SKIP] No completed main experiments found in {exp_dir}')
        continue

    print(f'\n[{variant}] Found experiments: {datasets}')

    results, metric_names = collect_results(exp_dir, datasets, ensemble)

    label = VARIANT_LABELS.get(variant, variant)
    print_section(label, datasets, results, metric_names)

    for dataset in datasets:
        score = results[dataset]
        metric = metric_names.get(dataset, '?')
        val = f'{score:.6f}' if score is not None else 'N/A'
        all_tsv_rows.append(f'{variant}\t{dataset}\t{val}\t{metric}')

# ── write TSV ──────────────────────────────────────────────────────────────────

tsv_path = args.tsv or (BASE_DIR / 'exp' / 'results_main.tsv')
with open(tsv_path, 'w', encoding='utf-8') as f:
    f.write('variant\texperiment\ttest_score\tmetric\n')
    for row in all_tsv_rows:
        f.write(row + '\n')

print(f'\nTSV saved → {tsv_path}')
